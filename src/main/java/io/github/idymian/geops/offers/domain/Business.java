package io.github.idymian.geops.offers.domain;

import java.time.Instant;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;

/**
 * A local business, owned by exactly one PROVIDER user.
 *
 * <p>The owner is referenced by id only (no JPA relation to the identity context),
 * so bounded contexts stay decoupled. The PostGIS {@code location} column is
 * generated by the database from latitude/longitude and is not mapped here.
 */
@Entity
@Table(name = "businesses")
public class Business {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(name = "owner_id", nullable = false, unique = true, updatable = false)
    private UUID ownerId;

    @Column(nullable = false)
    private String name;

    private String description;

    private String phone;

    @Column(nullable = false)
    private String address;

    @Column(nullable = false)
    private double latitude;

    @Column(nullable = false)
    private double longitude;

    @Column(name = "logo_url")
    private String logoUrl;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Business() {
        // for JPA
    }

    public Business(UUID ownerId) {
        this.ownerId = ownerId;
    }

    public void updateProfile(String name, String description, String phone, String address,
                              double latitude, double longitude) {
        this.name = name.strip();
        this.description = blankToNull(description);
        this.phone = blankToNull(phone);
        this.address = address.strip();
        this.latitude = latitude;
        this.longitude = longitude;
    }

    private static String blankToNull(String value) {
        return value == null || value.isBlank() ? null : value.strip();
    }

    @PrePersist
    void onCreate() {
        createdAt = Instant.now();
        updatedAt = createdAt;
    }

    @PreUpdate
    void onUpdate() {
        updatedAt = Instant.now();
    }

    public UUID getId() {
        return id;
    }

    public UUID getOwnerId() {
        return ownerId;
    }

    public String getName() {
        return name;
    }

    public String getDescription() {
        return description;
    }

    public String getPhone() {
        return phone;
    }

    public String getAddress() {
        return address;
    }

    public double getLatitude() {
        return latitude;
    }

    public double getLongitude() {
        return longitude;
    }

    public String getLogoUrl() {
        return logoUrl;
    }
}
